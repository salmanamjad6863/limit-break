/**
 * Community (SYSTEMS.md §5): handles, follows, the feed, reactions, comments, reports, monthly boards.
 * Weight, measurements, food and location are never part of any community payload.
 */
import { z } from 'zod';
import { HeroClass, Rank } from './common';

/** 3–20 chars, lowercase letters, digits, "_" and "."; no leading/trailing/double dots. */
export const Handle = z
  .string()
  .trim()
  .toLowerCase()
  .regex(/^(?!.*\.\.)(?!\.)(?!.*\.$)[a-z0-9_.]{3,20}$/, 'Use 3–20 letters, numbers, "_" or "."');

export const STICKERS = ['respect', 'limit_broken', 'ganbatte', 'beast_mode', 'nice_form', 'lets_go'] as const;
export const Sticker = z.enum(STICKERS);
export type Sticker = z.infer<typeof Sticker>;

export const Visibility = z.enum(['public', 'followers', 'private']);
export const CommentsMode = z.enum(['all', 'followers', 'off']);
export const FeedTab = z.enum(['following', 'global', 'rank']);
export type FeedTab = z.infer<typeof FeedTab>;

/** What other hunters see about someone (never the real name). */
export const HunterCardDto = z.object({
  userId: z.string(),
  handle: z.string(),
  heroId: z.string().nullable(),
  heroClass: HeroClass.nullable(),
  rank: Rank,
  level: z.number().int(),
  powerLevel: z.number().int(),
});
export type HunterCardDto = z.infer<typeof HunterCardDto>;

/** Milestone posts are generated by the server; the payload describes what happened. */
export const MilestonePayload = z.discriminatedUnion('kind', [
  z.object({ kind: z.literal('rank_up'), from: Rank, to: Rank }),
  z.object({ kind: z.literal('pr'), exerciseId: z.string(), e1rmKg: z.number(), previousKg: z.number().nullable() }),
  z.object({ kind: z.literal('level'), level: z.number().int() }),
  z.object({ kind: z.literal('streak'), days: z.number().int() }),
]);
export type MilestonePayload = z.infer<typeof MilestonePayload>;

/** Optional workout card on a progress post: exercises and PRs, never body weight. */
export const WorkoutCard = z.object({
  workoutId: z.string(),
  name: z.string(),
  minutes: z.number(),
  workingSets: z.number().int(),
  volumeKg: z.number(),
  prs: z.array(z.object({ exerciseId: z.string(), e1rmKg: z.number() })),
});
export type WorkoutCard = z.infer<typeof WorkoutCard>;

/** A photo on a progress post. `url` is a short-lived signed read URL (null when it can't be signed). */
export const PostMediaDto = z.object({
  id: z.string(),
  url: z.string().nullable(),
  width: z.number().int(),
  height: z.number().int(),
  /** the author sees their own photos while they're pending */
  status: z.enum(['pending', 'visible', 'rejected']),
});
export type PostMediaDto = z.infer<typeof PostMediaDto>;

export const PostDto = z.object({
  id: z.string(),
  type: z.enum(['milestone', 'progress']),
  author: HunterCardDto,
  body: z.string().nullable(),
  milestone: MilestonePayload.nullable(),
  workout: WorkoutCard.nullable(),
  media: z.array(PostMediaDto).default([]),
  visibility: Visibility,
  /** the author's own posts can be "pending" while moderation reviews them */
  status: z.enum(['pending', 'visible', 'hidden']),
  commentsMode: CommentsMode,
  respectCount: z.number().int(),
  commentCount: z.number().int(),
  myReaction: Sticker.nullable(),
  mine: z.boolean(),
  createdAt: z.string(),
});
export type PostDto = z.infer<typeof PostDto>;

export const FeedResponse = z.object({ posts: z.array(PostDto), nextCursor: z.string().nullable() });
export type FeedResponse = z.infer<typeof FeedResponse>;

export const CreatePostInput = z.object({
  /** client-generated: retries never double-post */
  id: z.uuid(),
  body: z.string().trim().min(1).max(500),
  visibility: Visibility.default('followers'),
  commentsMode: CommentsMode.default('all'),
  /** attach one of your own workouts as a card */
  workoutId: z.uuid().nullable().default(null),
  /** up to 4 photos uploaded via POST /community/media/sign; needs public-post trust (T2) */
  media: z
    .array(z.object({
      id: z.uuid(),
      storageKey: z.string().min(1).max(200),
      width: z.number().int().positive(),
      height: z.number().int().positive(),
    }))
    .max(4)
    .default([]),
});
export type CreatePostInput = z.input<typeof CreatePostInput>;

/** Ask for a signed upload target for one photo (private `community-media` bucket; never proxied by the API). */
export const SignPostMediaInput = z.object({ id: z.uuid() });
export type SignPostMediaInput = z.input<typeof SignPostMediaInput>;
export const SignPostMediaResponse = z.object({
  id: z.string(),
  uploadUrl: z.string(),
  /** pass back in CreatePostInput.media[].storageKey */
  storageKey: z.string(),
  maxBytes: z.number().int(),
});
export type SignPostMediaResponse = z.infer<typeof SignPostMediaResponse>;

export const CommentDto = z.object({
  id: z.string(),
  postId: z.string(),
  parentId: z.string().nullable(),
  author: HunterCardDto,
  body: z.string(),
  status: z.enum(['pending', 'visible', 'hidden']),
  mine: z.boolean(),
  createdAt: z.string(),
});
export type CommentDto = z.infer<typeof CommentDto>;

export const CreateCommentInput = z.object({
  id: z.uuid(),
  body: z.string().trim().min(1).max(280),
  /** one level of replies */
  parentId: z.uuid().nullable().default(null),
});
export type CreateCommentInput = z.input<typeof CreateCommentInput>;

export const ReactInput = z.object({ sticker: Sticker });

export const ReportInput = z.object({
  targetType: z.enum(['post', 'comment', 'profile']),
  targetId: z.string().min(1).max(64),
  reason: z.enum(['harassment', 'hate', 'sexual', 'self_harm', 'spam', 'cheating', 'other']),
  details: z.string().trim().max(500).optional(),
});
export type ReportInput = z.infer<typeof ReportInput>;

/** Earned access (SYSTEMS.md §5.4), computed from account age, workouts, level and standing. */
export const TrustLevel = z.union([z.literal(0), z.literal(1), z.literal(2), z.literal(3)]);
export type TrustLevel = z.infer<typeof TrustLevel>;

export const CommunityMeResponse = z.object({
  /** null = hasn't picked a handle yet */
  handle: z.string().nullable(),
  isPublic: z.boolean(),
  bio: z.string().nullable(),
  trustLevel: TrustLevel,
  /** guests and under-18s get a read-only community */
  isGuest: z.boolean(),
  isMinor: z.boolean(),
  can: z.object({
    react: z.boolean(),
    follow: z.boolean(),
    comment: z.boolean(),
    post: z.boolean(),
    postPublic: z.boolean(),
    appearOnBoards: z.boolean(),
  }),
  /** what unlocks the next level, in plain words */
  nextUnlock: z.string().nullable(),
  followers: z.number().int(),
  following: z.number().int(),
  /** shows the moderation queue entry point (the server still checks on every call) */
  isModerator: z.boolean().default(false),
});
export type CommunityMeResponse = z.infer<typeof CommunityMeResponse>;

export const UpdateCommunityProfileInput = z.object({
  handle: Handle.optional(),
  isPublic: z.boolean().optional(),
  bio: z.string().trim().max(160).nullable().optional(),
});
export type UpdateCommunityProfileInput = z.infer<typeof UpdateCommunityProfileInput>;

export const PublicProfileResponse = z.object({
  hunter: HunterCardDto,
  bio: z.string().nullable(),
  followers: z.number().int(),
  following: z.number().int(),
  iFollow: z.boolean(),
  followsMe: z.boolean(),
  posts: z.array(PostDto),
});
export type PublicProfileResponse = z.infer<typeof PublicProfileResponse>;

export const BoardId = z.enum(['consistent', 'xp', 'improved']);
export type BoardId = z.infer<typeof BoardId>;
export const Division = z.enum(['all', 'ED', 'CB', 'AS']);
export type Division = z.infer<typeof Division>;

export const BoardRow = z.object({ place: z.number().int(), hunter: HunterCardDto, score: z.number() });
export const BoardResponse = z.object({
  board: BoardId,
  division: Division,
  month: z.string(),
  /** results become final on day 3 of the next month, after review */
  final: z.boolean(),
  rows: z.array(BoardRow),
  me: BoardRow.nullable(),
  /** why I'm not on the board (guest, under 18, account too new, profile private, no handle) */
  meIneligible: z.string().nullable(),
});
export type BoardResponse = z.infer<typeof BoardResponse>;

export const ModerationItem = z.object({
  targetType: z.enum(['post', 'comment']),
  targetId: z.string(),
  body: z.string().nullable(),
  author: z.string(),
  status: z.string(),
  reasons: z.array(z.string()),
  openReports: z.number().int(),
  createdAt: z.string(),
});
export type ModerationItem = z.infer<typeof ModerationItem>;

export const ModerationDecisionInput = z.object({ action: z.enum(['approve', 'hide']), reason: z.string().trim().min(1).max(200) });
