#!/usr/bin/env node
/**
 * Generates src/features/visuals/bundled.generated.ts from assets/exercises/<id>/{loop,side,thumb}.webp
 * so Tier-1 demo clips ship inside the app (VISUALS.md §3.5). Metro needs static require() calls,
 * which is why this map is generated instead of built at runtime.
 *
 *   pnpm --filter @lb/mobile media:bundle
 */
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets/exercises');
const out = join(root, 'src/features/visuals/bundled.generated.ts');
const KINDS = ['loop', 'side', 'thumb'];
const LIMIT = { loop: 400_000, side: 400_000, thumb: 25_000 }; // §3.5 budgets

const ids = existsSync(dir) ? readdirSync(dir).filter((d) => statSync(join(dir, d)).isDirectory()).sort() : [];
const lines = [];
let total = 0;
const over = [];
for (const id of ids) {
  const parts = [];
  for (const k of KINDS) {
    const f = join(dir, id, `${k}.webp`);
    if (!existsSync(f)) continue;
    const size = statSync(f).size;
    total += size;
    if (size > LIMIT[k]) over.push(`${id}/${k}.webp ${(size / 1000).toFixed(0)} KB > ${LIMIT[k] / 1000} KB`);
    parts.push(`${k}: require('../../../assets/exercises/${id}/${k}.webp')`);
  }
  if (parts.length) lines.push(`  '${id}': { ${parts.join(', ')} },`);
}

writeFileSync(
  out,
  `// GENERATED by scripts/bundle-media.mjs — do not edit. Tier-1 demo clips bundled in the app.
export const bundledMedia: Record<string, { loop?: number; side?: number; thumb?: number }> = {
${lines.join('\n')}
};
`,
);
console.log(`bundled ${lines.length} exercise(s), ${(total / 1e6).toFixed(1)} MB → ${out.replace(root + '/', '')}`);
if (total > 25e6) over.push(`total ${(total / 1e6).toFixed(1)} MB > 25 MB Tier-1 budget`);
if (over.length) {
  console.error('Over budget:\n  ' + over.join('\n  '));
  process.exit(1);
}
